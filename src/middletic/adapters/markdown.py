"""Shared markdown rendering for instruction-file targets."""

from __future__ import annotations

import shlex

from middletic.adapters.base import AgentAdapter
from middletic.capabilities.degradation import render_cautions
from middletic.core.ir import UniversalIR

FOOTER = "_This block is generated by Middletic from `agent.toml`. Do not edit._"


class MarkdownAdapter(AgentAdapter):
    """Renders the IR as markdown and appends degradation cautions."""

    def generate(self, ir: UniversalIR) -> dict[str, str]:
        sections = render_sections(ir)
        cautions = render_cautions(self.display_name, self.capabilities, ir)
        if cautions:
            sections.append(cautions)
        sections.append(FOOTER)
        return {self.filename: "\n\n".join(sections)}


def render_sections(ir: UniversalIR) -> list[str]:
    sections: list[str] = [f"# {ir.project_name}"]
    if ir.project_description:
        sections.append(ir.project_description)

    if ir.role:
        sections.append(f"## Role\n\n{ir.role}")

    behavior: list[str] = []
    if ir.tone:
        behavior.append(f"Communicate in a {ir.tone} tone.")
    if ir.explain_changes:
        behavior.append("Explain the changes you make and why.")
    if ir.confirm_destructive_actions:
        behavior.append(
            "Ask for confirmation before destructive actions "
            "(deleting files, force-pushing, dropping data)."
        )
    if behavior:
        sections.append("## Behavior\n\n" + _bullets(behavior))

    code: list[str] = []
    if ir.language:
        code.append(f"Primary language: {ir.language}.")
    if ir.code_style:
        code.append(f"Code style: {ir.code_style}")
    if code:
        sections.append("## Code\n\n" + _bullets(code))

    testing: list[str] = []
    if ir.tests_required:
        testing.append("Tests are required for every change.")
    if ir.test_command:
        testing.append(f"Run tests with `{ir.test_command}`.")
    if testing:
        sections.append("## Testing\n\n" + _bullets(testing))

    git: list[str] = []
    if ir.branch_prefix:
        git.append(f"Prefix new branches with `{ir.branch_prefix}`.")
    if ir.require_clean_worktree:
        git.append("Require a clean git worktree before starting work.")
    if git:
        sections.append("## Git\n\n" + _bullets(git))

    if ir.allow or ir.deny:
        perms = [f"Allowed: `{item}`" for item in ir.allow]
        perms.extend(f"Denied: `{item}`" for item in ir.deny)
        sections.append("## Permissions\n\n" + _bullets(perms))

    if ir.mcp_servers:
        servers: list[str] = []
        for server in ir.mcp_servers:
            invocation = shlex.join([server.command, *server.args])
            line = f"`{server.name}`: `{invocation}`"
            if server.env_keys:
                line += " (env: " + ", ".join(f"`{k}`" for k in server.env_keys) + ")"
            servers.append(line)
        sections.append("## MCP Servers\n\n" + _bullets(servers))

    return sections


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items)
